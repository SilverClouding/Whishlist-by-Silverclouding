export const normalizeLocale = (rawLocale) => {
  if (!rawLocale || typeof rawLocale !== "string") return "en";
  const code = rawLocale.trim().toLowerCase().split(/[-_]/)[0];
  const supported = ["en", "es", "fr", "de", "it", "pt"];
  return supported.includes(code) ? code : "en";
};

export const resolveLocale = (request, session = null) => {
  try {
    const url = new URL(request.url);
    const queryLocale = url.searchParams.get("locale");
    if (queryLocale) return normalizeLocale(queryLocale);

    if (session?.locale) return normalizeLocale(session.locale);

    const acceptLang = request.headers?.get("accept-language");
    if (acceptLang) return normalizeLocale(acceptLang.split(",")[0]);
  } catch {}
  return "en";
};

